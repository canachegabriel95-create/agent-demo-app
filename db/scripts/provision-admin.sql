-- Provisions the initial administrator. Idempotent: an existing user is never modified.
--
-- Required psql variables (nothing is hardcoded in this file):
--   admin_email          sign-in email of the administrator
--   admin_name           full name (2-100 characters)
--   admin_password_hash  Identity V3 hash from: dotnet run --project backend/tools/ContentReview.Tools -- hash-password
--
-- Usage (see docs/password-hashing.md and scripts/provision-admin.sh / .ps1):
--   psql "$CONNECTION" -v admin_email="$ADMIN_EMAIL" -v admin_name="$ADMIN_NAME" \
--        -v admin_password_hash="$HASH" -f db/scripts/provision-admin.sql
--
-- Everything runs in one transaction and stops at the first error, so invalid input writes nothing.
-- The hash is never echoed in messages. Do not log the psql command line with the real hash.

\set ON_ERROR_STOP on

-- An undefined psql variable would otherwise be sent to the server as literal text; default to empty
-- so the validation below reports it.
\if :{?admin_email}
\else
  \set admin_email ''
\endif
\if :{?admin_name}
\else
  \set admin_name ''
\endif
\if :{?admin_password_hash}
\else
  \set admin_password_hash ''
\endif

BEGIN;

SELECT set_config('provision.email', :'admin_email', true),
       set_config('provision.name', :'admin_name', true),
       set_config('provision.hash', :'admin_password_hash', true)
\gset provision_

DO $provision$
DECLARE
    v_email   text := btrim(current_setting('provision.email'));
    v_name    text := btrim(current_setting('provision.name'));
    v_hash    text := btrim(current_setting('provision.hash'));
    v_norm    text;
    v_id      uuid;
    v_role    text;
BEGIN
    IF v_email = '' THEN
        RAISE EXCEPTION 'admin_email is required (psql -v admin_email=...)';
    END IF;
    IF length(v_email) > 254 OR v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' THEN
        RAISE EXCEPTION 'admin_email is not a valid email address (max 254 characters)';
    END IF;
    IF length(v_name) < 2 OR length(v_name) > 100 THEN
        RAISE EXCEPTION 'admin_name is required and must be between 2 and 100 characters';
    END IF;
    IF v_hash = '' THEN
        RAISE EXCEPTION 'admin_password_hash is required (generate it with ContentReview.Tools hash-password)';
    END IF;
    IF length(v_hash) < 60 OR length(v_hash) > 512
       OR v_hash !~ '^AQAAAA[A-Za-z0-9+/]+={0,2}$' THEN
        RAISE EXCEPTION 'admin_password_hash is not an Identity V3 password hash (expected base64 starting with AQAAAA, generated by hash-password)';
    END IF;

    v_norm := lower(v_email);

    INSERT INTO users (id, email, normalized_email, password_hash, full_name, role, status, created_at, updated_at)
    VALUES (gen_random_uuid(), v_email, v_norm, v_hash, v_name, 'Administrator', 'Active', now(), now())
    ON CONFLICT (normalized_email) DO NOTHING
    RETURNING id INTO v_id;

    IF v_id IS NULL THEN
        SELECT role INTO v_role FROM users WHERE normalized_email = v_norm;
        IF v_role = 'Administrator' THEN
            RAISE NOTICE 'Administrator already exists - no changes made';
        ELSE
            RAISE WARNING 'A user with this email already exists with role % - no changes made', v_role;
        END IF;
    ELSE
        INSERT INTO audit_events (id, occurred_at, actor_user_id, action, entity_type, entity_id, details)
        VALUES (gen_random_uuid(), now(), NULL, 'AdministratorProvisioned', 'User', v_id,
                jsonb_build_object('email', v_norm));
        RAISE NOTICE 'Administrator created';
    END IF;
END
$provision$;

COMMIT;
